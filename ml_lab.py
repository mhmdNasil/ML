# POLYNOMIAL REGRESSION ON AUTO MPG DATASET

# 1. Import required libraries
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

from sklearn.model_selection import train_test_split
from sklearn.linear_model import LinearRegression
from sklearn.preprocessing import PolynomialFeatures
from sklearn.pipeline import make_pipeline
from sklearn.metrics import mean_squared_error, r2_score


# 2. Load the dataset
import pandas as pd

url = "https://archive.ics.uci.edu/ml/machine-learning-databases/auto-mpg/auto-mpg.data"

columns = [
    "mpg", "cylinders", "displacement",
    "horsepower", "weight", "acceleration",
    "model_year", "origin", "name"
]

df = pd.read_csv(
    url,
    sep=r"\s+",
    names=columns,
    na_values="?"
)

df.dropna(inplace=True)

print(df.head())

print("First 5 rows:")
print(df.head())

print("\nDataset information:")
print(df.info())

print("\nMissing values:")
print(df.isnull().sum())


# 3. Data preprocessing

# Convert horsepower into numeric format if present
if "horsepower" in df.columns:
    df["horsepower"] = pd.to_numeric(
        df["horsepower"], errors="coerce"
    )

# Remove missing values
df.dropna(inplace=True)

# Remove unnecessary name column
if "name" in df.columns:
    df.drop("name", axis=1, inplace=True)

print("\nDataset after preprocessing:")
print(df.shape)


# 4. Select independent and dependent variables

X = df[["displacement"]]
y = df["mpg"]

print("\nIndependent variable: Displacement")
print("Dependent variable: MPG")


# 5. Split the dataset into training and testing sets

X_train, X_test, y_train, y_test = train_test_split(
    X, y,
    test_size=0.20,
    random_state=42
)

print("\nTraining samples:", len(X_train))
print("Testing samples:", len(X_test))


# 6. Linear Regression

linear_model = LinearRegression()

linear_model.fit(X_train, y_train)

y_pred_linear = linear_model.predict(X_test)

linear_mse = mean_squared_error(y_test, y_pred_linear)
linear_r2 = r2_score(y_test, y_pred_linear)

print("\n========== LINEAR REGRESSION ==========")
print("MSE:", linear_mse)
print("R2 Score:", linear_r2)


# 7. Polynomial Regression with different degrees

degrees = [2, 3, 4, 5]

results = []

models = {}

for degree in degrees:

    poly_model = make_pipeline(
        PolynomialFeatures(degree=degree),
        LinearRegression()
    )

    # Train the model
    poly_model.fit(X_train, y_train)

    # Predict test data
    y_pred = poly_model.predict(X_test)

    # Calculate evaluation metrics
    mse = mean_squared_error(y_test, y_pred)
    r2 = r2_score(y_test, y_pred)

    # Store the trained model
    models[degree] = poly_model

    # Store results
    results.append({
        "Model": "Polynomial Degree " + str(degree),
        "MSE": mse,
        "R2 Score": r2
    })

    print("\n========== POLYNOMIAL DEGREE", degree, "==========")
    print("MSE:", mse)
    print("R2 Score:", r2)


# 8. Compare all models

comparison = pd.DataFrame([
    {
        "Model": "Linear Regression",
        "MSE": linear_mse,
        "R2 Score": linear_r2
    }
] + results)

print("\n========== MODEL COMPARISON ==========")
print(comparison.to_string(index=False))


# 9. Find the best model based on test MSE

best_index = comparison["MSE"].idxmin()
best_model = comparison.loc[best_index]

print("\n========== BEST MODEL ==========")
print("Best Model:", best_model["Model"])
print("Best MSE:", best_model["MSE"])
print("Best R2 Score:", best_model["R2 Score"])


# 10. Visualize actual data and regression curves

plt.figure(figsize=(12, 7))

# Actual data points
plt.scatter(
    X["displacement"],
    y,
    color="blue",
    alpha=0.5,
    label="Actual Data"
)

# Smooth values for plotting
X_plot = np.linspace(
    X["displacement"].min(),
    X["displacement"].max(),
    300
).reshape(-1, 1)

# Linear regression line
y_linear = linear_model.predict(X_plot)

plt.plot(
    X_plot,
    y_linear,
    color="red",
    linewidth=2,
    label="Linear Regression"
)

# Polynomial regression curves
for degree in degrees:

    y_poly = models[degree].predict(X_plot)

    plt.plot(
        X_plot,
        y_poly,
        linewidth=2,
        label="Polynomial Degree " + str(degree)
    )

plt.xlabel("Engine Displacement")
plt.ylabel("Miles Per Gallon (MPG)")

plt.title("Linear vs Polynomial Regression on Auto MPG Dataset")

plt.legend()
plt.grid(True)
plt.show()


# 11. Plot MSE comparison

