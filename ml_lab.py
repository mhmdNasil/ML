# 1. Import required libraries

import numpy as np
import matplotlib.pyplot as plt
import pandas as pd
import time

from tensorflow.keras.datasets import fashion_mnist

from sklearn.neighbors import KNeighborsClassifier
from sklearn.metrics import accuracy_score, precision_score
from sklearn.metrics import recall_score, f1_score

# ============================================================
# 2. LOAD FASHION MNIST DATASET FROM INTERNET
# ============================================================

(X_train, y_train), (X_test, y_test) = fashion_mnist.load_data()

print("Training images:", X_train.shape)
print("Testing images:", X_test.shape)

# ============================================================
# 3. DISPLAY CLASS NAMES
# ============================================================

class_names = [
    "T-shirt/top",
    "Trouser",
    "Pullover",
    "Dress",
    "Coat",
    "Sandal",
    "Shirt",
    "Sneaker",
    "Bag",
    "Ankle boot"
]

# ============================================================
# 4. DISPLAY SAMPLE IMAGES
# ============================================================

plt.figure(figsize=(10, 5))

for i in range(10):
    plt.subplot(2, 5, i + 1)
    plt.imshow(X_train[i], cmap="gray")
    plt.title(class_names[y_train[i]])
    plt.axis("off")

plt.tight_layout()
plt.show()

# ============================================================
# 5. PREPROCESS THE DATASET
# ============================================================

# Normalize pixel values from 0-255 to 0-1

X_train = X_train.astype("float32") / 255.0
X_test = X_test.astype("float32") / 255.0

# Convert 28x28 images into 784-dimensional vectors

X_train = X_train.reshape(X_train.shape[0], 784)
X_test = X_test.reshape(X_test.shape[0], 784)

print("After preprocessing:")
print("Training data:", X_train.shape)
print("Testing data:", X_test.shape)

# ============================================================
# 6. USE A SUBSET TO REDUCE COMPUTATION TIME
# ============================================================

# Full dataset contains 60,000 training and 10,000 testing images.
# KNN is computationally expensive, so use a subset.

X_train = X_train[:10000]
y_train = y_train[:10000]

X_test = X_test[:2000]
y_test = y_test[:2000]

print("\nSamples used for KNN:")
print("Training:", X_train.shape)
print("Testing :", X_test.shape)

# ============================================================
# 7. IMPLEMENT KNN FOR DIFFERENT K VALUES
# ============================================================

k_values = [1, 3, 5, 7, 9]

results = []

for k in k_values:

    print("\n================================")
    print("K =", k)
    print("================================")

    # Create KNN classifier

    knn = KNeighborsClassifier(
        n_neighbors=k,
        metric="euclidean",
        n_jobs=-1
    )

    # Train the model

    start_train = time.time()

    knn.fit(X_train, y_train)

    training_time = time.time() - start_train

    # Predict test labels

    start_test = time.time()

    y_pred = knn.predict(X_test)

    prediction_time = time.time() - start_test

    # Evaluate model

    accuracy = accuracy_score(y_test, y_pred)

    precision = precision_score(
        y_test, y_pred,
        average="weighted",
        zero_division=0
    )

    recall = recall_score(
        y_test, y_pred,
        average="weighted",
        zero_division=0
    )

    f1 = f1_score(
        y_test, y_pred,
        average="weighted",
        zero_division=0
    )

    print("Accuracy :", round(accuracy, 4))
    print("Precision:", round(precision, 4))
    print("Recall   :", round(recall, 4))
    print("F1 Score :", round(f1, 4))

    print("Training Time  :", round(training_time, 4), "seconds")
    print("Prediction Time:", round(prediction_time, 4), "seconds")

    results.append([
        k,
        accuracy,
        precision,
        recall,
        f1,
        training_time,
        prediction_time
    ])

# ============================================================
# 8. DISPLAY COMPARISON TABLE
# ============================================================

results_df = pd.DataFrame(
    results,
    columns=[
        "K",
        "Accuracy",
        "Precision",
        "Recall",
        "F1 Score",
        "Training Time",
        "Prediction Time"
    ]
)

print("\nFINAL PERFORMANCE COMPARISON")

print(results_df.to_string(index=False))

# ============================================================
# 9. PLOT ACCURACY VS K
# ============================================================

plt.figure(figsize=(8, 5))

plt.plot(
    results_df["K"],
    results_df["Accuracy"],
    marker="o"
)

plt.xlabel("K Value")
plt.ylabel("Accuracy")
plt.title("KNN Accuracy for Different K Values")
plt.xticks(k_values)
plt.grid(True)

plt.show()

# ============================================================
# 10. PLOT PREDICTION TIME VS K
# ============================================================

plt.figure(figsize=(8, 5))

plt.plot(
    results_df["K"],
    results_df["Prediction Time"],
    marker="o"
)

plt.xlabel("K Value")
plt.ylabel("Prediction Time (seconds)")
plt.title("KNN Prediction Time Comparison")
