# ============================================================
# DECISION TREE CLASSIFIER USING ID3
# ONLINE RETAIL DATASET
# ============================================================

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

from sklearn.model_selection import train_test_split
from sklearn.tree import DecisionTreeClassifier, plot_tree
from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    classification_report,
    confusion_matrix,
    ConfusionMatrixDisplay
)
from sklearn.preprocessing import LabelEncoder

# ============================================================
# 1. LOAD DATASET
# ============================================================

file_path = "https://github.com/dbdmg/data-science-lab/raw/master/datasets/online_retail.csv"

df = pd.read_csv(file_path)

print("Original dataset shape:", df.shape)
print("\nFirst 5 rows:")
print(df.head())

# ============================================================
# 2. PREPROCESSING
# ============================================================

# Remove rows without CustomerID
df = df.dropna(subset=["CustomerID"])

# Remove cancelled invoices
df = df[~df["InvoiceNo"].astype(str).str.startswith("C")]

# Keep only positive quantity and price
df = df[(df["Quantity"] > 0) & (df["UnitPrice"] > 0)]

# Convert InvoiceDate to datetime
df["InvoiceDate"] = pd.to_datetime(df["InvoiceDate"])

# Calculate total price for each transaction
df["TotalPrice"] = df["Quantity"] * df["UnitPrice"]

print("\nAfter preprocessing:", df.shape)

# ============================================================
# 3. CREATE CUSTOMER-LEVEL FEATURES
# ============================================================

# Reference date = day after the last transaction
reference_date = df["InvoiceDate"].max() + pd.Timedelta(days=1)

customer_df = df.groupby("CustomerID").agg(
    Recency=("InvoiceDate",
             lambda x: (reference_date - x.max()).days),

    TotalTransactions=("InvoiceNo", "nunique"),

    TotalQuantity=("Quantity", "sum"),

    TotalSpent=("TotalPrice", "sum")
).reset_index()

print("\nCustomer-level dataset:")
print(customer_df.head())

print("\nCustomer dataset shape:", customer_df.shape)

# ============================================================
# 4. CREATE TARGET VARIABLE
# ============================================================

# Divide customers into 3 equal-sized groups
customer_df["ValueSegment"] = pd.qcut(
    customer_df["TotalSpent"],
    q=3,
    labels=["Low", "Medium", "High"]
)

print("\nSegment distribution:")
print(customer_df["ValueSegment"].value_counts())

# ============================================================
# 5. PREPARE X AND Y
# ============================================================

features = [
    "Recency",
    "TotalTransactions",
    "TotalQuantity",
    "TotalSpent"
]

X = customer_df[features]
y = customer_df["ValueSegment"]

# Encode target
label_encoder = LabelEncoder()
y_encoded = label_encoder.fit_transform(y)

print("\nTarget classes:")
print(label_encoder.classes_)

# ============================================================
# 6. TRAIN-TEST SPLIT
# ============================================================

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y_encoded,
    test_size=0.20,
    random_state=42,
    stratify=y_encoded
)

print("\nTraining samples:", X_train.shape[0])
print("Testing samples:", X_test.shape[0])

# ============================================================
# 7. ID3 DECISION TREE
# ============================================================

# ID3 uses entropy as the splitting criterion
model = DecisionTreeClassifier(
    criterion="entropy",
    random_state=42,
    max_depth=4
)

model.fit(X_train, y_train)

# ============================================================
# 8. PREDICTION
# ============================================================

y_pred = model.predict(X_test)

# ============================================================
# 9. EVALUATION
# ============================================================

accuracy = accuracy_score(y_test, y_pred)

precision = precision_score(
    y_test,
    y_pred,
    average="weighted"
)

recall = recall_score(
    y_test,
    y_pred,
    average="weighted"
)

f1 = f1_score(
    y_test,
    y_pred,
    average="weighted"
)

print("\n========== MODEL PERFORMANCE ==========")

print("Accuracy :", accuracy)
print("Precision:", precision)
print("Recall   :", recall)
print("F1-score :", f1)

print("\nClassification Report:")
print(
    classification_report(
        y_test,
        y_pred,
        target_names=label_encoder.classes_
    )
)

# ============================================================
# 10. CONFUSION MATRIX
# ============================================================

cm = confusion_matrix(y_test, y_pred)

print("\nConfusion Matrix:")
print(cm)

disp = ConfusionMatrixDisplay(
    confusion_matrix=cm,
    display_labels=label_encoder.classes_
)

disp.plot()
plt.title("Confusion Matrix - ID3 Decision Tree")
plt.show()

# ============================================================
# 11. VISUALIZE DECISION TREE
# ============================================================

plt.figure(figsize=(20, 10))

plot_tree(
    model,
    feature_names=features,
    class_names=label_encoder.classes_,
    filled=True,
    rounded=True,
    fontsize=10
)

plt.title("ID3 Decision Tree for Customer Segmentation")
plt.show()

# ============================================================
# 12. FEATURE IMPORTANCE
# ============================================================

importance = pd.DataFrame({
    "Feature": features,
    "Importance": model.feature_importances_
})

importance = importance.sort_values(
    by="Importance",
    ascending=False
)

print("\n========== FEATURE IMPORTANCE ==========")
print(importance)

# ============================================================
# 13. FEATURE IMPORTANCE GRAPH
# ============================================================

plt.figure(figsize=(8, 5))

plt.bar(
    importance["Feature"],
    importance["Importance"]
)

plt.xlabel("Features")
plt.ylabel("Importance")
plt.title("Feature Importance - ID3 Decision Tree")

plt.xticks(rotation=30)
plt.tight_layout()
plt.show()

